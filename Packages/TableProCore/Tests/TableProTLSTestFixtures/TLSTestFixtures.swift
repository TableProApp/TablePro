    public static func der(_ pem: String) -> Data {
        let body = pem
            .split(separator: "\n")
            .drop { !$0.hasPrefix("-----BEGIN") }
            .dropFirst()
            .prefix { !$0.hasPrefix("-----END") }
            .filter { !$0.contains(":") }
            .joined()
        return Data(base64Encoded: body) ?? Data()
    }

    public static func data(_ pems: String...) -> Data {
        Data(pems.joined(separator: "\n").utf8)
    }
