// A binary property list whose array at each level holds the next level twice, so `levels` levels
// stand for 2^levels leaves. PropertyListSerialization writes every path out, so it is built by hand.
enum SharedReferencePropertyList {
    static func make(levels: Int) -> Data {
        var objects: [[UInt8]] = [
            [0xD1, 1, 2],
            [0x58] + Array("settings".utf8),
            [0xA1, 3],
        ]
        for level in 0 ..< levels {
            let next = UInt8(4 + level)
            objects.append([0xA2, next, next])
        }
        objects.append([0x51] + Array("x".utf8))

        var data = Data("bplist00".utf8)
        var offsets: [UInt8] = []
        for object in objects {
            offsets.append(UInt8(data.count))
            data.append(contentsOf: object)
        }
        let offsetTableOffset = data.count
        data.append(contentsOf: offsets)
        // Trailer: six unused bytes, one-byte offsets and references, then three big-endian UInt64s.
        data.append(contentsOf: [0, 0, 0, 0, 0, 0, 1, 1])
        for field in [objects.count, 0, offsetTableOffset] {
            data.append(contentsOf: (0 ..< 8).reversed().map { UInt8(truncatingIfNeeded: field >> ($0 * 8)) })
        }
        return data
    }
}
