    @Test("A token scope of more than 32 parts is refused, within the length cap")
    func scopePartCap() throws {
        let folder = try ThemeImportFolder()
        defer { folder.remove() }
        for (parts, name) in [(32, "fits.json"), (33, "over.json")] {
            let scope = Array(repeating: "a", count: parts).joined(separator: ".")
            try folder.write(
                ##"{"colors": {"editor.background": "#101010"}, "tokenColors": [{"scope": "source.sql \##(scope)", "settings": {"foreground": "#FFFFFF"}}]}"##,
                as: name
            )
        }

        #expect(folder.refusal(importing: "fits.json") == nil)
        #expect(folder.refusal(importing: "over.json") == .tokenScopeHasTooManyParts(limit: 32))
    }

    @Test("A theme that nests arrays or objects past 32 levels is refused", .timeLimit(.minutes(1)))
    func deepNestingIsRefused() throws {
        let folder = try ThemeImportFolder()
        defer { folder.remove() }
        let nested = String(repeating: "[", count: 40) + String(repeating: "]", count: 40)
        try folder.write(##"{"colors": {"editor.background": "#101010"}, "tokenColors": \##(nested)}"##, as: "deep.json")
        try folder.write(String(repeating: "[", count: 100_000) + String(repeating: "]", count: 100_000), as: "deeper.json")

        #expect(folder.refusal(importing: "deep.json") == .nestingTooDeep(limit: 32))
        #expect(folder.refusal(importing: "deeper.json") == .notATheme)
    }
