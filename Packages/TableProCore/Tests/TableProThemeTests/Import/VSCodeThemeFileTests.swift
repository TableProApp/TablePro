        #expect(folder.refusal(importing: "self.json") == .includeCycle("self.json"))
    }

    @Test("Includes nest at most eight levels deep")
    func includeDepthIsCapped() throws {
        let folder = try ThemeImportFolder()
        defer { folder.remove() }
        for level in 0 ..< 9 {
            try folder.write(##"{"include": "level\##(level + 1).json"}"##, as: "level\(level).json")
        }
        try folder.write(##"{"colors": {"editor.background": "#202020"}}"##, as: "level9.json")

        #expect(folder.refusal(importing: "level0.json") == .includeTooDeep(limit: 8))
        #expect(try folder.importTheme("level1.json").hex(.editorBackground) == "#202020")
    }

