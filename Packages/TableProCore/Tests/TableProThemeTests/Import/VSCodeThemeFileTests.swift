    @Test("A 220-byte binary tmTheme whose arrays share their children is refused at once", .timeLimit(.minutes(1)))
    func sharedReferenceTextMateTheme() throws {
        let folder = try ThemeImportFolder()
        defer { folder.remove() }
        let data = SharedReferencePropertyList.make(levels: 40)
        var format = PropertyListSerialization.PropertyListFormat.xml
        _ = try PropertyListSerialization.propertyList(from: data, options: [], format: &format)
        try folder.write(data, as: "x.tmTheme")
        try folder.write(##"{"tokenColors": "./x.tmTheme"}"##, as: "x-color-theme.json")

        #expect(format == .binary)
        #expect(data.count == 220)
        #expect(folder.refusal(importing: "x-color-theme.json") == .invalidTextMateTheme("./x.tmTheme"))
    }

