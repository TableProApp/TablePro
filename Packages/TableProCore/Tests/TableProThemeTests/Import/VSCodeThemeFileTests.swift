    @Test("JSONC comments, trailing commas and a byte order mark parse, and strings keep their slashes")
    func jsoncParses() throws {
        let folder = try ThemeImportFolder()
        defer { folder.remove() }
        try folder.write(
            """
            \u{FEFF}// Generated by VS Code
            {
              "name": "Slashes // and /* stars */", // a comment after a value
              /* a block comment */ "type": "dark",
              "colors": {
                "editor.background": "#101820",
                //"editor.foreground": "#000000",
                "editor.foreground": "#E0E0E0",
              },
              "tokenColors": [
                {"scope": "string", "settings": {"foreground": "#A0C0E0",},},
              ],
            }
            """,
            as: "commented.json"
        )

        let theme = try folder.importTheme("commented.json")

        #expect(theme.name == "Slashes // and /* stars */")
        #expect(theme.hex(.editorBackground) == "#101820")
        #expect(theme.hex(.editorText) == "#E0E0E0")
        #expect(theme.hex(.syntaxString) == "#A0C0E0")
    }

    @Test("An include loads first, so the including file's colors and rules win, and \"default\" drops a color")
    func includeOrderAndDefault() throws {
        let folder = try ThemeImportFolder()
        defer { folder.remove() }
        try folder.write(
            """
            {"colors": {"editor.background": "#111111", "editor.foreground": "#222222", "editorLineNumber.foreground": "#333333"},
             "tokenColors": [{"scope": "keyword", "settings": {"foreground": "#444444"}}]}
            """,
            as: "base.json"
        )
        try folder.write(
            """
            {"include": "./base.json",
             "colors": {"editor.background": "#AAAAAA", "editorLineNumber.foreground": "default"},
             "tokenColors": [{"scope": "keyword", "settings": {"foreground": "#BBBBBB"}}]}
            """,
            as: "main.json"
        )

        let theme = try folder.importTheme("main.json")

        #expect(theme.hex(.editorBackground) == "#AAAAAA")
        #expect(theme.hex(.editorText) == "#222222")
        #expect(theme.hex(.editorLineNumber) == nil)
        #expect(theme.hex(.gridRowNumber) == nil)
        #expect(theme.hex(.syntaxKeyword) == "#BBBBBB")
    }

    @Test("A nested include resolves from its own folder and may reach back into the chosen one")
    func nestedIncludeResolvesFromItsFolder() throws {
        let folder = try ThemeImportFolder()
        defer { folder.remove() }
        try folder.write(##"{"colors": {"editor.background": "#123456"}}"##, as: "base.json")
        try folder.write(##"{"include": "../base.json", "colors": {"editor.foreground": "#654321"}}"##, as: "parts/middle.json")
        try folder.write(##"{"include": "parts/middle.json"}"##, as: "main.json")

        let theme = try folder.importTheme("main.json")

        #expect(theme.hex(.editorBackground) == "#123456")
        #expect(theme.hex(.editorText) == "#654321")
    }

    @Test("A path out of the theme's folder is refused, by .., an absolute path, ~ or a symlink")
    func pathsOutsideTheFolderAreRefused() throws {
        let outside = try ThemeImportFolder()
        defer { outside.remove() }
        let secret = try outside.write(##"{"colors": {"editor.background": "#000000"}}"##, as: "secret.json")

        let folder = try ThemeImportFolder()
        defer { folder.remove() }
        let traversal = "../\(outside.url.lastPathComponent)/secret.json"
        try folder.write(##"{"include": "\##(traversal)"}"##, as: "traversal.json")
        try folder.write(##"{"include": "\##(secret.path)"}"##, as: "absolute.json")
        try folder.write(##"{"include": "~/secret.json"}"##, as: "home.json")
        try folder.link("link.json", to: secret)
        try folder.write(##"{"include": "./link.json"}"##, as: "symlink.json")
        try folder.write(##"{"colors": {"editor.background": "#101010"}, "tokenColors": "\##(traversal)"}"##, as: "tokens.json")

        #expect(folder.refusal(importing: "traversal.json") == .includeOutsideFolder(traversal))
        #expect(folder.refusal(importing: "absolute.json") == .includeOutsideFolder(secret.path))
        #expect(folder.refusal(importing: "home.json") == .includeOutsideFolder("~/secret.json"))
        #expect(folder.refusal(importing: "symlink.json") == .includeOutsideFolder("./link.json"))
        #expect(folder.refusal(importing: "tokens.json") == .includeOutsideFolder(traversal))
    }

    @Test("A symlink that stays inside the folder is followed")
    func symlinkInsideTheFolderIsFollowed() throws {
        let folder = try ThemeImportFolder()
        defer { folder.remove() }
        let target = try folder.write(##"{"colors": {"editor.background": "#0A0B0C"}}"##, as: "real/base.json")
        try folder.link("base.json", to: target)
        try folder.write(##"{"include": "base.json"}"##, as: "main.json")

        #expect(try folder.importTheme("main.json").hex(.editorBackground) == "#0A0B0C")
    }

    @Test("A theme that includes itself, directly or through another file, is refused")
    func cyclesAreRefused() throws {
        let folder = try ThemeImportFolder()
        defer { folder.remove() }
        try folder.write(##"{"include": "./b.json", "colors": {"editor.background": "#111111"}}"##, as: "a.json")
        try folder.write(##"{"include": "./a.json"}"##, as: "b.json")
        try folder.write(##"{"include": "self.json"}"##, as: "self.json")

