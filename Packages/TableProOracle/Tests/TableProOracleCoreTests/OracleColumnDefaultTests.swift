import Foundation
@testable import TableProOracleCore
import Testing

/// The stored texts here are the ones `USER_TAB_COLS.DATA_DEFAULT` returned on Oracle 23ai for the DDL named beside
/// each, read through OracleNIO. `scripts/probes/check-oracle-column-defaults.sh` checks the same shapes against a live server.
struct OracleColumnDefaultTests {
    private func clause(
        _ storedText: String?,
        isIdentity: Bool = false,
        isVirtual: Bool = false,
        onNull: OracleDefaultOnNull = .never
    ) -> String? {
        OracleColumnDefault(storedText: storedText, isIdentity: isIdentity, isVirtual: isVirtual, onNull: onNull).clause
    }

    /// `DEFAULT 7` followed by a newline and the indentation of the next line.
    @Test func testTrailingWhitespaceTheDDLLeftBehindIsTrimmed() {
        #expect(clause("7\n  ") == "7")
        #expect(clause("7    ") == "7")
        #expect(clause("''\n") == "''")
    }

    @Test func testNoDefaultIsNil() {
        #expect(clause(nil) == nil)
        #expect(clause("") == nil)
        #expect(clause(" \n ") == nil)
    }

    /// `DEFAULT NULL` is stored as typed, so `default null` reads `null`. It is a default, unlike SQL NULL.
    @Test func testAnExplicitNullDefaultReadsAsNullWhateverItsCase() {
        #expect(clause("null") == "NULL")
        #expect(clause("NULL") == "NULL")
        #expect(clause("Null\n  ") == "NULL")
    }

    @Test func testLiteralsAndExpressionsKeepTheirSpelling() {
        #expect(clause("'it''s'") == "'it''s'")
        #expect(clause("sys_guid()") == "sys_guid()")
        #expect(clause("current_timestamp") == "current_timestamp")
        #expect(clause("-1.5") == "-1.5")
        #expect(clause("(1 + 2)") == "(1 + 2)")
        #expect(clause("'null'") == "'null'")
    }

    /// `GENERATED BY DEFAULT AS IDENTITY` stores the sequence it draws from.
    @Test func testAnIdentityColumnHasNoDefault() {
        #expect(clause("\"PROBE\".\"ISEQ$$_73292\".nextval", isIdentity: true) == nil)
        #expect(clause("\"PROBE\".\"ISEQ$$_73292\".nextval", isIdentity: true, onNull: .onInsert) == nil)
    }

    /// `GENERATED ALWAYS AS (c_zero + 1) VIRTUAL` stores its expression.
    @Test func testAVirtualColumnHasNoDefault() {
        #expect(clause("\"C_ZERO\"+1", isVirtual: true) == nil)
    }

    private func generationExpression(_ storedText: String?, isIdentity: Bool = false, isVirtual: Bool) -> String? {
        OracleColumnDefault(storedText: storedText, isIdentity: isIdentity, isVirtual: isVirtual, onNull: .never)
            .generationExpression
    }

    /// `a + 1 /* c */` is stored rewritten as `"A"+1`, and `UPPER('x' || TO_CHAR(a))` as `UPPER('x'||TO_CHAR("A"))`.
    @Test func testAVirtualColumnReadsItsExpression() {
        #expect(generationExpression("\"A\"+1", isVirtual: true) == "\"A\"+1")
        #expect(generationExpression("UPPER('x'||TO_CHAR(\"A\"))\n  ", isVirtual: true) == "UPPER('x'||TO_CHAR(\"A\"))")
        #expect(generationExpression("\"A\"+1 -- note\n", isVirtual: true) == "\"A\"+1")
        #expect(generationExpression(" \n", isVirtual: true) == nil)
        #expect(generationExpression(nil, isVirtual: true) == nil)
    }

    @Test func testOnlyAVirtualColumnHasAnExpression() {
        #expect(generationExpression("5", isVirtual: false) == nil)
        #expect(generationExpression("\"PROBE\".\"ISEQ$$_73292\".nextval", isIdentity: true, isVirtual: false) == nil)
    }

    /// A sequence named in an ordinary `DEFAULT` is a default like any other.
    @Test func testASequenceDefaultOnAnOrdinaryColumnIsKept() {
        #expect(clause("\"PROBE\".\"MY_SEQ\".\"NEXTVAL\"") == "\"PROBE\".\"MY_SEQ\".\"NEXTVAL\"")
    }

    /// Restating `'x'` alone on a `DEFAULT ON NULL` column turned the semantics off and the column nullable, measured.
    @Test func testADefaultOnNullKeepsItsOnNull() {
        #expect(clause("'x'", onNull: .onInsert) == "ON NULL 'x'")
        #expect(clause("'u'\n  ", onNull: .onInsertAndUpdate) == "ON NULL FOR INSERT AND UPDATE 'u'")
    }

    /// `default 9 -- trailing comment` with the comma on the next line keeps the comment and its newline, and the
    /// newline is what stops it commenting out the rest of a statement the value is written into.
    @Test func testATrailingLineCommentGoesWithTheWhitespace() {
        #expect(clause("9 -- trailing comment\n  ") == "9")
        #expect(clause("'--' -- dashes\n  ") == "'--'")
    }

    @Test func testABlockCommentGoes() {
        #expect(clause("'A' /* active */\n  ") == "'A'")
        #expect(clause("null /* none */") == "NULL")
    }

    /// `default 1 -- one` then `+ 2` on the next line.
    @Test func testACommentInsideAMultiLineDefaultKeepsItsNewline() {
        #expect(clause("1 -- one\n   + 2\n  ") == "1 \n   + 2")
    }

    @Test func testCommentMarkersInsideQuotesAreText() {
        #expect(clause("q'[it's -- x]' -- real\n  ") == "q'[it's -- x]'")
        #expect(clause("nq'{a''b}'\n") == "nq'{a''b}'")
        #expect(clause("Q'!/* x */!'") == "Q'!/* x */!'")
        #expect(clause("'a /* b */ c'") == "'a /* b */ c'")
        #expect(clause("\"COL--NAME\" -- note\n") == "\"COL--NAME\"")
    }

    /// `q'` opens an alternative quote only at the start of a word; inside a longer name the quote is ordinary, so
    /// `'it''s'` still reads its doubled quote as an escape.
    @Test func testAQInsideANameDoesNotOpenAnAlternativeQuote() {
        #expect(OracleSQLCommentStripper("seq'a''b -- c' -- d").stripped() == "seq'a''b -- c' ")
    }

    @Test func testOnNullFollowsBothFlags() {
        #expect(OracleDefaultOnNull(onInsert: false, onUpdate: false) == .never)
        #expect(OracleDefaultOnNull(onInsert: true, onUpdate: false) == .onInsert)
        #expect(OracleDefaultOnNull(onInsert: true, onUpdate: true) == .onInsertAndUpdate)
        #expect(OracleDefaultOnNull(onInsert: false, onUpdate: true) == .never)
    }
}
