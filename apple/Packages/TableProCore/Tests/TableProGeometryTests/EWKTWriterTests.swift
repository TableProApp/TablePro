    @Test func testEveryMeasuredValueSpellsAsPostGISDoes() {
        for (hex, ewkt) in Self.measured {
            #expect(EWKTWriter.string(fromHex: hex) == ewkt, "\(hex)")
        }
    }

    @Test func testLowercaseHexReads() {
        let hex = "0101000020e6100000000000000000f03f0000000000000040"
        #expect(EWKTWriter.string(fromHex: hex) == "SRID=4326;POINT(1 2)")
    }

    @Test func testBigEndianReads() {
        #expect(EWKTWriter.string(fromHex: "00000000013FF00000000000004000000000000000") == "POINT(1 2)")
    }

    // ST_AsEWKT gives -0.1277583 and 51.5074 for this London point, which match no row when written back.
    @Test func testOrdinatesKeepEveryDigitTheyNeedToReadBack() {
        let values = [-0.12775830000000002, 51.507400000000004, 1.2345678901234568e-05, 0.30000000000000004, 1e15, 1e-8]
        for value in values {
            #expect(Double(EWKTWriter.ordinate(value)) == value, "\(value)")
        }
        #expect(EWKTWriter.ordinate(-0.12775830000000002) == "-0.12775830000000002")
        #expect(EWKTWriter.ordinate(1.2345678901234568e-05) == "0.000012345678901234568")
        #expect(EWKTWriter.ordinate(1e15) == "1e+15")
        #expect(EWKTWriter.ordinate(1e-8) == "1e-8")
        #expect(EWKTWriter.ordinate(-0.0) == "-0")
        #expect(EWKTWriter.ordinate(0.0) == "0")
    }

    @Test func testAnythingButWholeEWKBIsRefused() {
        let point = "0101000000000000000000F03F0000000000000040"
        #expect(EWKTWriter.string(fromHex: "") == nil)
        #expect(EWKTWriter.string(fromHex: "POINT(1 2)") == nil)
        #expect(EWKTWriter.string(fromHex: String(point.dropLast(2))) == nil)
        #expect(EWKTWriter.string(fromHex: point + "00") == nil)
        // Type 99 does not exist; 13 and 14 are abstract.
        #expect(EWKTWriter.string(fromHex: "0163000000000000000000F03F0000000000000040") == nil)
        #expect(EWKTWriter.string(fromHex: "010D000000000000000000F03F0000000000000040") == nil)
        // A MULTIPOINT holding a LINESTRING.
        #expect(EWKTWriter.string(fromHex: "010400000001000000010200000000000000") == nil)
    }

    @Test func testCountsBeyondTheBytesLeftAreRefused() {
        #expect(EWKTWriter.string(fromHex: "0102000000FFFFFFFF") == nil)
        #expect(EWKTWriter.string(fromHex: "0107000000FFFFFFFF") == nil)
    }

    @Test func testNestingPastTheLimitIsRefused() {
        let wrappers = SpatialLimits.maximumNestingDepth - 1
        let allowed = String(repeating: "010700000001000000", count: wrappers) + "010700000000000000"
        let expected = String(repeating: "GEOMETRYCOLLECTION(", count: wrappers) + "GEOMETRYCOLLECTION EMPTY"
            + String(repeating: ")", count: wrappers)
        #expect(EWKTWriter.string(fromHex: allowed) == expected)
        #expect(EWKTWriter.string(fromHex: "010700000001000000" + allowed) == nil)
    }
