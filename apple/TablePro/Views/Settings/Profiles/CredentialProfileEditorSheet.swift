import SwiftUI
import TableProPluginKit

/// One credential profile: the name every connection picks it by, the username, and where the
/// password comes from.
struct CredentialProfileEditorSheet: View {
    @Environment(\.dismiss) private var dismiss

    let existingProfile: CredentialProfile?
    var initialPassword: String?
    /// Which engine's secrets to offer first, so a profile promoted from a Postgres connection
    /// does not open on MySQL's fields.
    var initialDatabaseType: DatabaseType?
    var onSave: ((CredentialProfile) -> Void)?
    var onDelete: (() -> Void)?

    @State private var name: String = ""
    @State private var username: String = ""
    @State private var passwordKind: PasswordKind = .stored
    @State private var password: String = ""
    @State private var passwordWasPrefilled = false
    @State private var sourceKind: PasswordSourceKind = .file
    @State private var sourceValue: String = ""
    @State private var sourceField: String = ""
    @State private var commandReuseSeconds: Int?
    @State private var vaultAccess = VaultAccessDraft()

    @State private var secureFieldType: DatabaseType = .mysql
    @State private var secureFieldValues: [String: String] = [:]

    @State private var showingDeleteConfirmation = false
    @State private var dependentCount = 0
    @State private var saveError: String?

    /// Read once when the sheet opens. `body` reads `nameIsUnique` and `isStored` several times per
    /// pass, and each one used to decode the whole profiles file off disk, on every keystroke.
    @State private var otherProfileNames: [String] = []
    @State private var isStored = false
    @State private var secureFields: [ConnectionField] = []
    /// False when a keychain read failed rather than finding nothing. Saving then must not
    /// treat an empty field as the user clearing a secret: a rename while the keychain was
    /// locked would delete the password of every connection on the profile.
    @State private var secretsWereReadable = true

    private var storage: CredentialProfileStorage { .shared }

    private var trimmedName: String { name.trimmingCharacters(in: .whitespaces) }

    private var isValid: Bool {
        guard !trimmedName.isEmpty else { return false }
        guard nameIsUnique else { return false }
        if passwordKind == .source {
            return testedSource != nil
        }
        return true
    }

    private var usernameComesFromSource: Bool {
        passwordKind == .source && sourceKind.suppliesUsername
    }

    /// Two profiles with one name are indistinguishable in every picker that offers them, which is
    /// the reason the system's own profile editors refuse it.
    private var nameIsUnique: Bool {
        !otherProfileNames.contains {
            $0.compare(trimmedName, options: [.caseInsensitive, .diacriticInsensitive]) == .orderedSame
        }
    }

    var body: some View {
        VStack(spacing: 0) {
            Form {
                Section(String(localized: "Profile")) {
                    TextField(String(localized: "Name"), text: $name, prompt: Text("Production reader"))
                        .accessibilityIdentifier("credential-profile-name")
                    if !trimmedName.isEmpty && !nameIsUnique {
                        Label(
                            String(localized: "Another profile already has this name."),
                            systemImage: "exclamationmark.triangle.fill"
                        )
                        .font(.caption)
                        .foregroundStyle(.yellow)
                    }
                    TextField(
                        String(localized: "Username"),
                        text: $username,
                        prompt: usernameComesFromSource ? Text("Generated by Vault") : Text("app_reader")
                    )
                    .disabled(usernameComesFromSource)
                    .accessibilityIdentifier("credential-profile-username")
                }

                if !secretsWereReadable {
                    Section {
                        Label(
                            String(localized: "The Keychain could not be read, so the stored secrets are not shown. Editing the name is safe; they are left as they are."),
                            systemImage: "exclamationmark.triangle.fill"
                        )
                        .font(.caption)
                        .foregroundStyle(.yellow)
                    }
                }
                passwordSection
                secureFieldsSection
            }
            .formStyle(.grouped)

            Divider()
            bottomBar
        }
        .frame(minWidth: 480, idealHeight: 460)
        .onAppear(perform: load)
    }

    // MARK: - Password

    @ViewBuilder
    private var passwordSection: some View {
        Section(String(localized: "Password")) {
            Picker(String(localized: "Source"), selection: $passwordKind) {
                ForEach(PasswordKind.allCases) { kind in
                    Text(kind.displayName).tag(kind)
                }
            }
            .accessibilityIdentifier("credential-profile-password-kind")

            switch passwordKind {
            case .stored:
                RevealablePasswordField(
                    title: String(localized: "Password"),
                    text: $password,
                    requiresAuthentication: passwordWasPrefilled
                )
            case .prompt:
                Text("Every connection using this profile asks for the password once each time TablePro runs.")
                    .font(.caption)
                    .foregroundStyle(.secondary)
            case .pgpass:
                Text("Looked up in ~/.pgpass by the host, port, database and username of the PostgreSQL-family connection that is opening. Other connections ask for the password.")
                    .font(.caption)
                    .foregroundStyle(.secondary)
            case .source:
                Picker(String(localized: "Read From"), selection: $sourceKind) {
                    ForEach(PasswordSourceKind.allCases) { kind in
                        Text(kind.displayName).tag(kind)
                    }
                }
                TextField(sourceKind.valueLabel, text: $sourceValue, prompt: Text(sourceKind.placeholder))
                if let fieldLabel = sourceKind.fieldLabel {
                    TextField(fieldLabel, text: $sourceField, prompt: Text(sourceKind.fieldPlaceholder))
                }
                if sourceKind == .vaultDatabaseRole {
                    vaultAccessRows
                }
                if sourceKind == .command {
                    Picker(String(localized: "Reuse Result For"), selection: $commandReuseSeconds) {
                        Text("Never").tag(Int?.none)
                        ForEach(Self.reuseChoices(including: commandReuseSeconds), id: \.self) { seconds in
                            Text(Self.reuseLabel(seconds)).tag(Int?.some(seconds))
                        }
                    }
                    .accessibilityIdentifier("credential-profile-command-reuse")
                    Text(String(localized: """
                        {host}, {port}, {user} and {database} become the opening connection's values, \
                        already quoted. The command also gets them as TABLEPRO_HOST, TABLEPRO_PORT, \
                        TABLEPRO_USER and TABLEPRO_DATABASE.
                        """))
                        .font(.caption)
                        .foregroundStyle(.secondary)
                }
                Text(sourceKind == .vaultDatabaseRole
                    ? String(localized: "It stays on this Mac and never syncs, because it names where your Vault token is sent.")
                    : String(localized: "It stays on this Mac and never syncs, because it can name a command to run."))
                    .font(.caption)
                    .foregroundStyle(.secondary)
                if let testedSource {
                    PasswordSourceTestView(
                        source: testedSource,
                        context: { testContext },
                        refusal: {
                            Self.testRefusal(
                                for: testedSource,
                                storedSource: storedSource,
                                storeIsTrusted: storage.storeIsTrusted
                            )
                        }
                    )
                    if sourceKind == .command, mentionsConnectionDetails {
                        Text("A test here has no connection to take the host, port and database from.")
                            .font(.caption)
                            .foregroundStyle(.secondary)
                    }
                }
            }
        }
    }

    @ViewBuilder
    private var vaultAccessRows: some View {
        TextField(
            String(localized: "Vault Address"),
            text: $vaultAccess.address,
            prompt: Text(verbatim: ProcessInfo.processInfo.environment["VAULT_ADDR"] ?? "https://vault.example.com:8200")
        )
        .accessibilityIdentifier("credential-profile-vault-address")
        Picker(String(localized: "Sign In With"), selection: Binding(
            get: { vaultAccess.method },
            set: { vaultAccess.selectMethod($0) }
        )) {
            ForEach(VaultAccessDraft.Method.allCases) { method in
                Text(method.displayName).tag(method)
            }
        }
        .accessibilityIdentifier("credential-profile-vault-method")
        switch vaultAccess.method {
        case .token:
            Text("Reads VAULT_TOKEN, or ~/.vault-token from vault login.")
                .font(.caption)
                .foregroundStyle(.secondary)
        case .appRole:
            TextField(String(localized: "Role ID"), text: $vaultAccess.roleId)
                .accessibilityIdentifier("credential-profile-vault-role-id")
            TextField(
                String(localized: "Secret ID File"),
                text: $vaultAccess.secretIdPath,
                prompt: Text(verbatim: "~/.vault/approle-secret-id")
            )
            .accessibilityIdentifier("credential-profile-vault-secret-id-path")
            TextField(String(localized: "Auth Mount"), text: $vaultAccess.mount, prompt: Text(verbatim: VaultAuthMethod.defaultAppRoleMount))
        case .oidc:
            TextField(String(localized: "OIDC Role"), text: $vaultAccess.oidcRole, prompt: Text("Default role"))
            TextField(String(localized: "Auth Mount"), text: $vaultAccess.mount, prompt: Text(verbatim: VaultAuthMethod.defaultOIDCMount))
            Text("Your browser opens to sign in once per launch. The role must allow http://localhost:8250/oidc/callback.")
                .font(.caption)
                .foregroundStyle(.secondary)
        }
        Text("Each connection signs in as a new database user. TablePro renews the lease while connected, revokes it on disconnect, and never saves the generated password.")
            .font(.caption)
            .foregroundStyle(.secondary)
    }

    // MARK: - Test Source

    private var testedSource: PasswordSource? {
        guard !sourceValue.trimmingCharacters(in: .whitespaces).isEmpty else { return nil }
        if sourceKind == .vaultDatabaseRole {
            guard !sourceField.trimmingCharacters(in: .whitespaces).isEmpty, vaultAccess.isComplete else { return nil }
        }
        return sourceKind.source(value: sourceValue, field: sourceField, reuseSeconds: nil, vaultAccess: vaultAccess)
    }

    private var storedSource: PasswordSource? {
        guard isStored, case .source(let source) = existingProfile?.passwordMode else { return nil }
        return source
    }

    private var testContext: ConnectionScriptContext {
        ConnectionScriptContext(
            connectionId: existingProfile?.id ?? UUID(),
            connectionName: "",
            host: "",
            port: 0,
            user: username.trimmingCharacters(in: .whitespaces),
            database: ""
        )
    }

    private var mentionsConnectionDetails: Bool {
        sourceValue.contains("TABLEPRO_") || testContext.substitutingPlaceholders(in: sourceValue) != sourceValue
    }

    // A source typed here is the user's own; one read back unchanged from a profiles file something else wrote is not.
    static func testRefusal(
        for source: PasswordSource,
        storedSource: PasswordSource?,
        storeIsTrusted: Bool
    ) -> PasswordSourceResolver.ResolutionError? {
        guard !storeIsTrusted, let storedSource, source == normalizedLikeTheFields(storedSource) else { return nil }
        return .profileStoreNotTrusted
    }

    // The fields trim what they hold, so the stored value is compared the same way or padding alone would pass for an edit.
    private static func normalizedLikeTheFields(_ source: PasswordSource) -> PasswordSource {
        let (kind, value, field) = PasswordSourceKind.decompose(source)
        let vaultAccess = source.vaultDatabaseRole.map(VaultAccessDraft.init) ?? VaultAccessDraft()
        return kind.source(value: value, field: field, reuseSeconds: nil, vaultAccess: vaultAccess)
    }

    // MARK: - Secure fields

    @ViewBuilder
    private var secureFieldsSection: some View {
        Section {
            Picker(String(localized: "For"), selection: $secureFieldType) {
                ForEach(DatabaseType.allKnownTypes, id: \.self) { type in
                    Text(type.rawValue).tag(type)
                }
            }
            .onChange(of: secureFieldType) { _ in reloadSecureFields() }
            if secureFields.isEmpty {
                Text("This database type signs in with the username and password above.")
                    .font(.caption)
                    .foregroundStyle(.secondary)
            } else {
                ForEach(secureFields, id: \.id) { field in
                    ConnectionFieldRow(field: field, value: secureFieldBinding(for: field))
                }
            }
        } header: {
            Text(String(localized: "Additional Secrets"))
        } footer: {
            Text("A connection reads only the secrets its own database type declares, so one profile can carry several engines' keys.")
                .font(.caption)
                .foregroundStyle(.secondary)
        }
    }

    private func reloadSecureFields() {
        secureFields = PluginManager.shared.additionalConnectionFields(for: secureFieldType).filter(\.isSecure)
    }

    private func secureFieldBinding(for field: ConnectionField) -> Binding<String> {
        Binding(
            get: { secureFieldValues[field.id] ?? "" },
            set: { secureFieldValues[field.id] = $0 }
        )
    }

    // MARK: - Bottom bar

    private var bottomBar: some View {
        HStack {
            if isStored {
                Button(role: .destructive) {
                    dependentCount = storage.connectionsUsing(existingProfile?.id ?? UUID()).count
                    showingDeleteConfirmation = true
                } label: {
                    Text("Delete Profile")
                }
                .accessibilityIdentifier("credential-profile-delete")
                .alert(String(localized: "Delete Credential Profile?"), isPresented: $showingDeleteConfirmation) {
                    Button(String(localized: "Delete"), role: .destructive) { deleteProfile() }
                    Button(String(localized: "Cancel"), role: .cancel) {}
                } message: {
                    if dependentCount > 0 {
                        Text("^[\(dependentCount) connection](inflect: true) use this profile. They keep these credentials as their own.")
                    } else {
                        Text("This profile will be permanently deleted.")
                    }
                }
            }

            if let saveError {
                Label(saveError, systemImage: "exclamationmark.triangle.fill")
                    .font(.caption)
                    .foregroundStyle(.red)
                    .lineLimit(2)
            }

            Spacer()

            Button(String(localized: "Cancel")) { dismiss() }
                .keyboardShortcut(.cancelAction)
                .accessibilityIdentifier("credential-profile-cancel")
            Button(isStored ? String(localized: "Save") : String(localized: "Create")) { saveProfile() }
                .keyboardShortcut(.defaultAction)
                .disabled(!isValid)
                .accessibilityIdentifier("credential-profile-save")
        }
        .padding()
    }

    // MARK: - Actions

    private func load() {
        let profiles = storage.loadProfiles()
        otherProfileNames = profiles.filter { $0.id != existingProfile?.id }.map { $0.name }
        isStored = existingProfile.map { candidate in profiles.contains { $0.id == candidate.id } } ?? false
        if let initialDatabaseType {
            secureFieldType = initialDatabaseType
        }
        reloadSecureFields()

        guard let profile = existingProfile else { return }
        name = profile.name
        username = profile.username
        for fieldId in profile.secureFieldIds {
            if let value = storage.loadSecureField(fieldId: fieldId, for: profile.id) {
                secureFieldValues[fieldId] = value
            } else {
                secretsWereReadable = false
            }
        }

        switch profile.passwordMode {
        case .stored:
            passwordKind = .stored
            if let stored = storage.loadPassword(for: profile.id) {
                password = stored
            } else if let initialPassword {
                password = initialPassword
            } else if isStored {
                secretsWereReadable = false
            }
            passwordWasPrefilled = !password.isEmpty
        case .prompt:
            passwordKind = .prompt
        case .pgpass:
            passwordKind = .pgpass
        case .source(let source):
            passwordKind = .source
            (sourceKind, sourceValue, sourceField) = PasswordSourceKind.decompose(source)
            if case .command(_, let reuseSeconds) = source {
                commandReuseSeconds = reuseSeconds
            }
            if let role = source.vaultDatabaseRole {
                vaultAccess = VaultAccessDraft(role)
            }
        }
    }

    private func saveProfile() {
        let profileId = existingProfile?.id ?? UUID()
        let liveFields = secureFieldValues.filter { !$0.value.isEmpty }
        let profile = CredentialProfile(
            id: profileId,
            name: trimmedName,
            username: username.trimmingCharacters(in: .whitespaces),
            passwordMode: buildPasswordMode(),
            secureFieldIds: secretsWereReadable
                ? liveFields.keys.sorted()
                : Array(Set(existingProfile?.secureFieldIds ?? []).union(liveFields.keys)).sorted(),
            sortOrder: existingProfile?.sortOrder ?? 0
        )

        let persisted = isStored ? storage.updateProfile(profile) : storage.addProfile(profile)
        /// The keychain writes below are keyed by the profile id, so running them for a profile
        /// that never reached disk would leave secrets nothing can name.
        guard persisted else {
            saveError = String(localized: "Could not save the profile. Check disk space and permissions, then try again.")
            return
        }
        saveError = nil

        if case .stored = profile.passwordMode, !password.isEmpty {
            guard storage.savePassword(password, for: profileId) else {
                saveError = String(localized: "Could not save the password to the Keychain. Nothing was changed.")
                return
            }
        } else if secretsWereReadable {
            storage.deletePassword(for: profileId)
        }

        /// Only what was read back is eligible for deletion. A field whose value could not be read
        /// is still there and still in use.
        if secretsWereReadable {
            let removed = Set(existingProfile?.secureFieldIds ?? []).subtracting(liveFields.keys)
            for fieldId in removed {
                storage.deleteSecureField(fieldId: fieldId, for: profileId)
            }
        }
        for (fieldId, value) in liveFields where !storage.saveSecureField(value, fieldId: fieldId, for: profileId) {
            saveError = String(localized: "Could not save a secret to the Keychain. Nothing was changed.")
            return
        }

        onSave?(profile)
        dismiss()
    }

    private func buildPasswordMode() -> CredentialPasswordMode {
        switch passwordKind {
        case .stored: .stored
        case .prompt: .prompt
        case .pgpass: .pgpass
        case .source:
            .source(sourceKind.source(
                value: sourceValue,
                field: sourceField,
                reuseSeconds: commandReuseSeconds,
                vaultAccess: vaultAccess
            ))
        }
    }

    private static let reusePresets = [300, 900, 3_600, 28_800]

    private static func reuseChoices(including current: Int?) -> [Int] {
        guard let current, !reusePresets.contains(current) else { return reusePresets }
        return (reusePresets + [current]).sorted()
    }

    private static func reuseLabel(_ seconds: Int) -> String {
        Duration.seconds(seconds).formatted(.units(allowed: [.hours, .minutes, .seconds], width: .wide))
    }

    private func deleteProfile() {
        guard let profile = existingProfile else { return }
        guard storage.deleteProfile(profile) else {
            saveError = String(localized: "Could not delete the profile. Check disk space and permissions, then try again.")
            return
        }
        onDelete?()
        dismiss()
    }
}

// MARK: - Kinds

extension CredentialProfileEditorSheet {
    enum PasswordKind: String, CaseIterable, Identifiable {
        case stored, prompt, pgpass, source

        var id: String { rawValue }

        var displayName: String {
            switch self {
            case .stored: String(localized: "Saved in the Keychain")
            case .prompt: String(localized: "Ask every time")
            case .pgpass: String(localized: "~/.pgpass")
            case .source: String(localized: "Read from elsewhere")
            }
        }
    }
}
