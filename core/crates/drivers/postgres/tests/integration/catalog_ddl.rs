/// A schema or database plan runs as the sidebar runs it: the batch
/// names the schema or database and no table.
async fn run(connection: &dyn Connection, plan: DdlPlan, name: &str) -> Result<WriteReport, DriverError> {
    let batch = plan.into_write_batch(TableRef::new(Some(name.to_owned()), ""));
    connection.write_batch(&batch, within(CALL)).await
}

async fn truncate(
    connection: &dyn Connection,
    table: &TableRef,
    options: TruncateTableOptions,
) -> Result<(), DriverError> {
    let plan = plan_truncate_table(connection.dialect().as_ref(), table, &options).expect("a truncate plan");
    connection
        .write_batch(&plan.into_write_batch(table.clone()), within(CALL))
        .await
        .map(|_| ())
}

/// The fixture's login, opening `database`.
fn options_in(fixture: &PostgresFixture, database: &str) -> ConnectOptions {
    let liveness = test_liveness();
    options_over(
        direct(fixture.host(), fixture.port(), &liveness),
        password(&fixture.password_credentials()),
        database,
        TlsConfig::disabled(),
        WorkspaceSettings::workspace(false),
        liveness,
    )
}

async fn value(connection: &dyn Connection, sql: &str) -> String {
    text(&scalar(connection, sql).await)
}

async fn databases(connection: &dyn Connection) -> Vec<String> {
    connection
        .list_databases(within(CALL))
        .await
        .expect("the databases")
        .into_iter()
        .map(|database| database.name)
        .collect()
}

async fn schemas(connection: &dyn Connection) -> Vec<String> {
    connection
        .list_schemas(within(CALL))
        .await
        .expect("the schemas")
        .into_iter()
        .map(|schema| schema.name)
        .collect()
}

/// The server refuses a referenced table on its own. CASCADE empties
/// the tables that reference it too, and only RESTART IDENTITY starts
/// the numbering again.
#[tokio::test(flavor = "multi_thread", worker_threads = 2)]
#[ignore = "requires docker"]
async fn a_truncate_cascades_to_referencing_tables_and_restarts_numbering_when_asked() {
    let fixture = start().await;
    let connection = connect(&fixture, false).await;
    let connection: &dyn Connection = connection.as_ref();
    setup(
        connection,
        &[
            "CREATE TABLE parent (id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, label text)",
            "CREATE TABLE child (id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, parent_id int REFERENCES parent)",
            "INSERT INTO parent (label) VALUES ('a'), ('b')",
            "INSERT INTO child (parent_id) VALUES (1), (2)",
        ],
    )
    .await;
    let parent = TableRef::new(Some("public".to_owned()), "parent");
    let counts = "SELECT (SELECT count(*) FROM parent) || '|' || (SELECT count(*) FROM child)";
    let cascade = TruncateTableOptions {
        cascade: true,
        ..TruncateTableOptions::default()
    };

    let refused = truncate(connection, &parent, TruncateTableOptions::default()).await;
    assert!(refused.is_err(), "{refused:?}");
    assert_eq!(value(connection, counts).await, "2|2");

    truncate(connection, &parent, cascade.clone())
        .await
        .expect("a cascading truncate");
    assert_eq!(value(connection, counts).await, "0|0");
    setup(connection, &["INSERT INTO parent (label) VALUES ('c')"]).await;
    assert_eq!(value(connection, "SELECT id FROM parent").await, "3");

    let restart = TruncateTableOptions {
        restart_identity: true,
        ..cascade
    };
    truncate(connection, &parent, restart)
        .await
        .expect("a truncate that restarts the numbering");
    assert_eq!(value(connection, counts).await, "0|0");
    setup(connection, &["INSERT INTO parent (label) VALUES ('d')"]).await;
    assert_eq!(value(connection, "SELECT id FROM parent").await, "1");
    connection.close().await.expect("a close");
}

#[tokio::test(flavor = "multi_thread", worker_threads = 2)]
#[ignore = "requires docker"]
async fn a_schema_is_created_for_its_owner_and_dropped_only_with_what_it_holds() {
    let fixture = start().await;
    let connection = connect(&fixture, false).await;
    let connection: &dyn Connection = connection.as_ref();
    let dialect = connection.dialect();
    let owner = fixture.password_credentials().username;
    let draft = SchemaDraft {
        name: "sales".to_owned(),
        owner: Some(owner.clone()),
    };

    let created = plan_create_schema(dialect.as_ref(), &draft).expect("a schema plan");
    run(connection, created, "sales").await.expect("the schema is created");
    setup(connection, &["CREATE TABLE sales.orders (id int)"]).await;
    assert!(schemas(connection).await.contains(&"sales".to_owned()));
    assert_eq!(
        value(
            connection,
            "SELECT nspowner::regrole::text FROM pg_namespace WHERE nspname = 'sales'"
        )
        .await,
        owner
    );

    let plain = plan_drop_schema(dialect.as_ref(), "sales", DropSchemaOptions::default()).expect("a drop plan");
    let refused = run(connection, plain, "sales").await;
    assert!(refused.is_err(), "{refused:?}");
    assert!(schemas(connection).await.contains(&"sales".to_owned()));

    let cascade =
        plan_drop_schema(dialect.as_ref(), "sales", DropSchemaOptions { cascade: true }).expect("a drop plan");
    run(connection, cascade, "sales").await.expect("the schema is dropped");
    assert!(!schemas(connection).await.contains(&"sales".to_owned()));
    connection.close().await.expect("a close");
}

/// The server refuses CREATE and DROP DATABASE inside a transaction, so
/// these pass only if the write sends them on their own. An encoding
/// and locale other than template1's are taken from template0.
#[tokio::test(flavor = "multi_thread", worker_threads = 2)]
#[ignore = "requires docker"]
async fn a_database_is_created_and_dropped_outside_a_transaction() {
    let fixture = start().await;
    let connection = connect(&fixture, false).await;
    let connection: &dyn Connection = connection.as_ref();
    let dialect = connection.dialect();
    let draft = DatabaseDraft {
        encoding: Some("LATIN1".to_owned()),
        locale: Some("C".to_owned()),
        ..DatabaseDraft::named("tp_latin")
    };

    let created = plan_create_database(dialect.as_ref(), &draft).expect("a create plan");
    assert_eq!(created.kind, WriteKind::DatabaseChanges);
    let report = run(connection, created, "tp_latin")
        .await
        .expect("CREATE DATABASE runs on its own");
    assert_eq!(report, WriteReport::new(vec![None]));
    assert_eq!(
        value(
            connection,
            "SELECT pg_encoding_to_char(encoding) || '|' || datcollate FROM pg_database WHERE datname = 'tp_latin'"
        )
        .await,
        "LATIN1|C"
    );
    assert!(databases(connection).await.contains(&"tp_latin".to_owned()));

    let dropped =
        plan_drop_database(dialect.as_ref(), "tp_latin", &DropDatabaseOptions::default()).expect("a drop plan");
    run(connection, dropped, "tp_latin")
        .await
        .expect("DROP DATABASE runs on its own");
    assert!(!databases(connection).await.contains(&"tp_latin".to_owned()));
    connection.close().await.expect("a close");
}

/// Each statement lands on its own, so a failure after the first reports
/// the first as applied rather than rolled back.
#[tokio::test(flavor = "multi_thread", worker_threads = 2)]
#[ignore = "requires docker"]
async fn a_database_change_that_fails_partway_reports_what_landed() {
    let fixture = start().await;
    let connection = connect(&fixture, false).await;
    let connection: &dyn Connection = connection.as_ref();

    let outcome = apply(
        connection,
        WriteKind::DatabaseChanges,
        &["CREATE DATABASE tp_twice", "CREATE DATABASE tp_twice"],
    )
    .await;

    assert!(
        matches!(
            outcome,
            Err(DriverError::PartiallyApplied {
                applied: 1,
                statement_index: 1,
                failed_outcome: StatementOutcome::Failed,
                ..
            })
        ),
        "{outcome:?}"
    );
    assert!(databases(connection).await.contains(&"tp_twice".to_owned()));
    connection.close().await.expect("a close");
}

/// Another workspace on the database keeps a plain drop out. The forced
/// one ends its sessions, and that workspace's next login finds the
/// database gone.
#[tokio::test(flavor = "multi_thread", worker_threads = 2)]
#[ignore = "requires docker"]
async fn a_forced_drop_ends_the_sessions_a_plain_drop_is_refused_for() {
    let fixture = start().await;
    let connection = connect(&fixture, false).await;
    let connection: &dyn Connection = connection.as_ref();
    let dialect = connection.dialect();
    let created = plan_create_database(dialect.as_ref(), &DatabaseDraft::named("tp_busy")).expect("a create plan");
    run(connection, created, "tp_busy")
        .await
        .expect("the database is created");
    let sibling = connect_with(options_in(&fixture, "tp_busy")).await;

    let plain = plan_drop_database(dialect.as_ref(), "tp_busy", &DropDatabaseOptions::default()).expect("a drop plan");
    let refused = run(connection, plain, "tp_busy").await;
    assert!(
        matches!(refused, Err(DriverError::RolledBack { statement_index: 0, .. })),
        "{refused:?}"
    );

    let force = DropDatabaseOptions {
        force: true,
        cluster: None,
    };
    let forced = plan_drop_database(dialect.as_ref(), "tp_busy", &force).expect("a forced drop on 13 and later");
    run(connection, forced, "tp_busy").await.expect("the forced drop runs");
    assert!(!databases(connection).await.contains(&"tp_busy".to_owned()));

    // The pooled connection the server ended may be found dead first,
    // before a login replaces it.
    let mut outcome = sibling.list_schemas(within(CALL)).await;
    if matches!(outcome, Err(DriverError::ConnectionLost { .. })) {
        outcome = sibling.list_schemas(within(CALL)).await;
    }
    assert!(
        matches!(&outcome, Err(DriverError::DatabaseNotFound { database }) if database == "tp_busy"),
        "{outcome:?}"
    );
    sibling.close().await.expect("a close");
    connection.close().await.expect("a close");
}

#[tokio::test(flavor = "multi_thread", worker_threads = 2)]
#[ignore = "requires docker"]
async fn the_new_database_options_list_the_servers_roles_templates_and_template1s_defaults() {
    let fixture = start().await;
    let connection = connect(&fixture, false).await;
    let user = fixture.password_credentials().username;

    let choices = connection
        .fetch_database_choices(within(CALL))
        .await
        .expect("the database choices");

    assert!(choices.owners.contains(&user), "{:?}", choices.owners);
    assert!(choices.owners.iter().all(|owner| !owner.starts_with("pg_")));
    for template in ["template0", "template1"] {
        assert!(
            choices.templates.contains(&template.to_owned()),
            "{:?}",
            choices.templates
        );
    }
    assert!(choices.encodings.contains(&"UTF8".to_owned()));
    assert!(choices.locales.contains(&"C".to_owned()), "{:?}", choices.locales);
    assert_eq!(choices.defaults.owner, Some(user));
    assert_eq!(choices.defaults.encoding.as_deref(), Some("UTF8"));
    assert!(choices.defaults.locale.is_some());
    connection.close().await.expect("a close");
}

