#![allow(clippy::unwrap_used, clippy::expect_used, clippy::panic)]

use tablepro_core::Value;
use tablepro_core::sql_dialect::build_insert_from_draft_touched;

use crate::{connect, start_pg};

#[tokio::test]
#[ignore = "requires docker"]
async fn a_draft_can_insert_an_explicit_null_over_a_default_and_a_typed_identity_value() {
    let (_c, opts) = start_pg().await;
    let conn = connect(opts).await;
    conn.execute("CREATE TABLE drafts (id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, status text DEFAULT 'new', note text)")
        .await
        .unwrap();
    let columns = conn.fetch_columns(None, "drafts").await.unwrap();

    let untouched = [Value::Null, Value::Null, Value::Text("a".into())];
    let (sql, params) = build_insert_from_draft_touched("postgres", None, "drafts", &columns, &untouched, &[]).unwrap();
    conn.execute_params(&sql, &params).await.unwrap();

    let nulled = [Value::Null, Value::Null, Value::Text("b".into())];
    let (sql, params) =
        build_insert_from_draft_touched("postgres", None, "drafts", &columns, &nulled, &[false, true, true]).unwrap();
    conn.execute_params(&sql, &params).await.unwrap();

    let typed = [Value::Int(100), Value::Null, Value::Text("c".into())];
    let (sql, params) =
        build_insert_from_draft_touched("postgres", None, "drafts", &columns, &typed, &[true, false, true]).unwrap();
    conn.execute_params(&sql, &params).await.unwrap();

    let rows = conn
        .query("SELECT id, status, note FROM drafts ORDER BY note")
        .await
        .unwrap()
        .rows;
    assert_eq!(rows[0][1], Value::Text("new".into()), "untouched: the default applies");
    assert_eq!(rows[1][1], Value::Null, "explicit NULL overrides the default");
    assert_eq!(rows[2][0], Value::Int(100), "typed identity value is kept");
}
