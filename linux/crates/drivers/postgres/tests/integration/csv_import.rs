//! The CSV import against PostgreSQL, through the same plan the app
//! runs.

use tablepro_core::import::CsvImportOptions;
use tablepro_core::{TableRef, Value};
use tablepro_test_support::import_csv;

use crate::support::{CALL, connect, rows, setup, start, within};

#[tokio::test(flavor = "multi_thread", worker_threads = 2)]
#[ignore = "requires docker"]
async fn a_file_keeps_its_ids_where_the_identity_takes_them() {
    let fixture = start().await;
    let connection = connect(&fixture, false).await;
    setup(
        connection.as_ref(),
        &[
            "CREATE TABLE serials (id serial PRIMARY KEY, name text)",
            "CREATE TABLE by_default (id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text)",
            "CREATE TABLE always (id int GENERATED ALWAYS AS IDENTITY PRIMARY KEY, name text)",
        ],
    )
    .await;

    for table in ["serials", "by_default", "always"] {
        import_csv(
            connection.as_ref(),
            &TableRef::new(Some("public".to_owned()), table),
            b"id,name\n100,ada\n",
            &CsvImportOptions::default(),
            within(CALL),
        )
        .await
        .unwrap_or_else(|failure| panic!("the import into {table}: {failure:?}"));
    }

    assert_eq!(
        rows(connection.as_ref(), "SELECT id FROM serials").await,
        vec![vec![Value::Int(100)]]
    );
    assert_eq!(
        rows(connection.as_ref(), "SELECT id FROM by_default").await,
        vec![vec![Value::Int(100)]]
    );
    assert_eq!(
        rows(connection.as_ref(), "SELECT id, name FROM always").await,
        vec![vec![Value::Int(1), Value::Text("ada".to_owned())]],
        "GENERATED ALWAYS refuses a value, so the server numbers the row"
    );
}
