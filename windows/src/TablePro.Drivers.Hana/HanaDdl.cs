using System.Globalization;
using System.Text;
using TablePro.Core.Schema;
using TablePro.Core.Sql;
using TablePro.Drivers.Hana.Localization;
using TablePro.Drivers.Odbc;

namespace TablePro.Drivers.Hana;

/// <summary>
/// HANA's statements for each structure change. HANA spells several of them its own way: ADD, ALTER and DROP take
/// parenthesised column lists, and columns and tables are renamed with RENAME statements. Pure, so tests pin them.
/// </summary>
internal static class HanaDdl
{
    public static readonly IReadOnlyList<string> CommonDataTypes =
    [
        "INTEGER", "BIGINT", "SMALLINT", "TINYINT", "DECIMAL(18,2)", "DECIMAL", "DOUBLE", "REAL", "NVARCHAR(255)", "NVARCHAR(5000)",
        "VARCHAR(255)", "NCLOB", "CLOB", "BOOLEAN", "DATE", "TIME", "SECONDDATE", "TIMESTAMP", "VARBINARY(255)", "BLOB", "ST_GEOMETRY",
    ];

    // NO ACTION is not a HANA keyword; leaving the clause out gives RESTRICT, HANA's default and its equivalent.
    private static readonly string[] ReferentialActions = ["CASCADE", "SET NULL", "SET DEFAULT"];

    private static readonly string[] CreatableIndexTypes = ["BTREE", "CPBTREE", "INVERTED VALUE", "INVERTED HASH", "INVERTED INDIVIDUAL", "FULLTEXT"];

    private static readonly string[] QuotedDefaultTypes =
        ["CHAR", "NCHAR", "VARCHAR", "NVARCHAR", "ALPHANUM", "SHORTTEXT", "CLOB", "NCLOB", "TEXT", "BINTEXT", "DATE", "TIME", "SECONDDATE", "TIMESTAMP"];

    private static readonly string[] DefaultFunctions =
    [
        "CURRENT_DATE", "CURRENT_TIME", "CURRENT_TIMESTAMP", "CURRENT_UTCDATE", "CURRENT_UTCTIME", "CURRENT_UTCTIMESTAMP",
        "CURRENT_USER", "SESSION_USER", "CURRENT_SCHEMA",
    ];

    private static SqlDialect Dialect => HanaDialect.Instance;

    public static IReadOnlyList<string> Build(ObjectName table, SchemaChange change) => change switch
    {
        CreateTable create => CreateTable(create),
        AddColumn add => AddColumn(table, add.Column),
        DropColumn drop => [string.Concat(AlterTable(table), " DROP (", Q(drop.Column), ")")],
        RenameColumn rename => [RenameColumn(table, rename.From, rename.To)],
        AlterColumn alter => AlterColumn(table, alter.Before, alter.After),
        CreateIndex index => [CreateIndex(table, index.Index)],
        DropIndex index => [string.Concat("DROP INDEX ", Qualify(table with { Name = index.Index }))],
        AddForeignKey key => [string.Concat(AlterTable(table), " ADD ", ForeignKey(table, key.ForeignKey))],
        DropForeignKey key => [string.Concat(AlterTable(table), " DROP CONSTRAINT ", Q(key.Name))],
        RenameTable rename => [string.Concat("RENAME TABLE ", Qualify(table), " TO ", Q(rename.NewName))],
        DropObject drop => DropObject(drop.Object, drop.Cascade) is { } sql ? [sql] : [],

        // HANA truncates without a CASCADE form.
        TruncateTable => [string.Concat("TRUNCATE TABLE ", Qualify(table))],
        _ => [],
    };

    /// <summary>
    /// Auto-increment is <c>GENERATED BY DEFAULT AS IDENTITY</c>, so an explicit key from an import still inserts. DEFAULT
    /// comes before the constraints, as HANA's grammar orders them.
    /// </summary>
    public static string ColumnSql(ColumnDefinition column, bool inlinePrimaryKey)
    {
        var sql = new StringBuilder(Q(column.Name)).Append(' ').Append(column.DataType.Trim());
        if (column.IsIdentity)
        {
            sql.Append(" GENERATED BY DEFAULT AS IDENTITY");
        }
        else if (!string.IsNullOrWhiteSpace(column.DefaultExpression))
        {
            sql.Append(" DEFAULT ").Append(column.DefaultExpression.Trim());
        }

        if (!column.IsNullable && !inlinePrimaryKey)
        {
            sql.Append(" NOT NULL");
        }

        if (inlinePrimaryKey)
        {
            sql.Append(" PRIMARY KEY");
        }

        return sql.ToString();
    }

    /// <summary>A column table, HANA's default store for analytics and the one HANA Cloud allows.</summary>
    public static List<string> CreateTable(CreateTable change)
    {
        var primaryKey = change.Columns.Where(c => c.IsPrimaryKey).Select(c => c.Name).ToList();
        var sql = new StringBuilder("CREATE COLUMN TABLE ").Append(Qualify(change.Table)).Append(" (\n  ");
        for (var i = 0; i < change.Columns.Count; i++)
        {
            if (i > 0)
            {
                sql.Append(",\n  ");
            }

            var column = change.Columns[i];
            sql.Append(ColumnSql(column, primaryKey.Count == 1 && column.IsPrimaryKey));
        }

        if (primaryKey.Count > 1)
        {
            sql.Append(",\n  PRIMARY KEY (").Append(JoinQuoted(primaryKey)).Append(')');
        }

        var statements = new List<string> { sql.Append("\n)").ToString() };
        foreach (var column in change.Columns)
        {
            if (!string.IsNullOrEmpty(column.Comment))
            {
                statements.Add(ColumnComment(change.Table, column.Name, column.Comment));
            }
        }

        return statements;
    }

    public static List<string> AddColumn(ObjectName table, ColumnDefinition column)
    {
        var statements = new List<string>(2) { string.Concat(AlterTable(table), " ADD (", ColumnSql(column, column.IsPrimaryKey), ")") };
        if (!string.IsNullOrEmpty(column.Comment))
        {
            statements.Add(ColumnComment(table, column.Name, column.Comment));
        }

        return statements;
    }

    public static string RenameColumn(ObjectName table, string from, string to) =>
        string.Concat("RENAME COLUMN ", Qualify(table), ".", Q(from), " TO ", Q(to));

    /// <summary>
    /// ALTER restates the column with its type, as HANA requires, and says NULL or NOT NULL outright. A removed default
    /// is written as <c>DEFAULT NULL</c>, since leaving it out keeps the old one. The rename runs last, so ALTER and
    /// the comment name the column as it was.
    /// </summary>
    public static List<string> AlterColumn(ObjectName table, ColumnDefinition before, ColumnDefinition after)
    {
        var statements = new List<string>(3);
        var typeChanged = !string.Equals(before.DataType.Trim(), after.DataType.Trim(), StringComparison.OrdinalIgnoreCase);
        var nullChanged = before.IsNullable != after.IsNullable;
        var beforeDefault = Trimmed(before.DefaultExpression);
        var afterDefault = Trimmed(after.DefaultExpression);
        var defaultChanged = !string.Equals(beforeDefault, afterDefault, StringComparison.Ordinal);
        if (typeChanged || nullChanged || defaultChanged)
        {
            var sql = new StringBuilder(AlterTable(table)).Append(" ALTER (").Append(Q(before.Name)).Append(' ').Append(after.DataType.Trim());
            if (afterDefault is not null)
            {
                sql.Append(" DEFAULT ").Append(afterDefault);
            }
            else if (beforeDefault is not null)
            {
                sql.Append(" DEFAULT NULL");
            }

            statements.Add(sql.Append(after.IsNullable ? " NULL)" : " NOT NULL)").ToString());
        }

        if (!string.Equals(before.Comment ?? string.Empty, after.Comment ?? string.Empty, StringComparison.Ordinal))
        {
            statements.Add(ColumnComment(table, before.Name, after.Comment));
        }

        if (!string.Equals(before.Name, after.Name, StringComparison.Ordinal))
        {
            statements.Add(RenameColumn(table, before.Name, after.Name));
        }

        return statements;
    }

    public static string CreateIndex(ObjectName table, IndexDefinition index) =>
        string.Concat(
            "CREATE ", index.IsUnique ? "UNIQUE " : string.Empty, "INDEX ", Qualify(table with { Name = index.Name }), " ON ",
            Qualify(table), " (", JoinQuoted(index.Columns), ")");

    public static string ForeignKey(ObjectName table, ForeignKeyDefinition key)
    {
        var referenced = key.ReferencedTable.Schema is null ? key.ReferencedTable with { Schema = table.Schema } : key.ReferencedTable;
        var sql = new StringBuilder();
        if (!string.IsNullOrEmpty(key.Name))
        {
            sql.Append("CONSTRAINT ").Append(Q(key.Name)).Append(' ');
        }

        sql.Append("FOREIGN KEY (").Append(JoinQuoted(key.Columns)).Append(") REFERENCES ").Append(Qualify(referenced));
        if (key.ReferencedColumns.Count > 0)
        {
            sql.Append(" (").Append(JoinQuoted(key.ReferencedColumns)).Append(')');
        }

        AppendAction(sql, " ON UPDATE ", key.OnUpdate);
        AppendAction(sql, " ON DELETE ", key.OnDelete);
        return sql.ToString();
    }

    public static string? DropObject(DatabaseObject obj, bool cascade)
    {
        var name = Qualify(obj.Name);
        var suffix = cascade ? " CASCADE" : string.Empty;
        return obj.Kind switch
        {
            ObjectKind.Table => string.Concat("DROP TABLE ", name, suffix),
            ObjectKind.View => string.Concat("DROP VIEW ", name, suffix),
            ObjectKind.Procedure => string.Concat("DROP PROCEDURE ", name, suffix),
            ObjectKind.Function => string.Concat("DROP FUNCTION ", name, suffix),
            ObjectKind.Sequence => string.Concat("DROP SEQUENCE ", name, suffix),
            ObjectKind.Trigger => "DROP TRIGGER " + name,
            _ => null,
        };
    }

    /// <summary>HANA removes a comment with <c>IS NULL</c>.</summary>
    public static string ColumnComment(ObjectName table, string column, string? comment) =>
        string.Concat("COMMENT ON COLUMN ", Qualify(table), ".", Q(column), " IS ", string.IsNullOrEmpty(comment) ? "NULL" : StringLiteral(comment));

    /// <summary>A Unicode literal, as the macOS driver writes them; NUL is dropped since HANA ends the text there.</summary>
    public static string StringLiteral(string value) =>
        string.Concat("N'", value.Replace("\0", string.Empty, StringComparison.Ordinal).Replace("'", "''", StringComparison.Ordinal), "'");

    /// <summary>
    /// ALTER SYSTEM DISCONNECT SESSION takes the connection id as a literal, so it is checked to be digits before it is
    /// written into the text.
    /// </summary>
    public static string Kill(object processId)
    {
        var id = Convert.ToString(processId, CultureInfo.InvariantCulture)?.Trim() ?? string.Empty;
        if (id.Length == 0 || !id.All(char.IsAsciiDigit))
        {
            throw new ArgumentException(HanaStrings.Format("Hana/NotAConnectionId", processId), nameof(processId));
        }

        return string.Concat("ALTER SYSTEM DISCONNECT SESSION '", id, "'");
    }

    /// <summary>
    /// The table as CREATE TABLE, built from the catalog when GET_OBJECT_DEFINITION is not open to the login: columns,
    /// the key, then each index HANA can recreate and each comment, as the macOS driver renders them.
    /// </summary>
    public static string TableDefinition(
        ObjectName table,
        bool isColumnTable,
        IReadOnlyList<object?[]> columnRows,
        IReadOnlyList<object?[]> indexRows,
        string? tableComment)
    {
        var lines = new List<string>(columnRows.Count + 1);
        var keys = new SortedList<int, string>();
        foreach (var row in columnRows)
        {
            var name = CatalogValues.Text(row[0]) ?? string.Empty;
            var typeName = CatalogValues.Text(row[1]) ?? "NVARCHAR";
            var definition = new StringBuilder("  ").Append(Q(name)).Append(' ')
                .Append(HanaCatalog.RenderType(typeName, CatalogValues.Int32(row[2]), CatalogValues.Int32(row[3])));
            var generation = CatalogValues.NonEmpty(row[5])?.ToUpperInvariant();
            var expression = CatalogValues.NonEmpty(CatalogValues.At(row, 9));
            switch (generation)
            {
                case "ALWAYS AS IDENTITY":
                    definition.Append(" GENERATED ALWAYS AS IDENTITY");
                    break;
                case "BY DEFAULT AS IDENTITY":
                    definition.Append(" GENERATED BY DEFAULT AS IDENTITY");
                    break;
                case "ALWAYS AS" when expression is not null:
                    definition.Append(" GENERATED ALWAYS AS (").Append(expression).Append(')');
                    break;
                case "ALWAYS CALCULATED AS" when expression is not null:
                    definition.Append(" AS (").Append(expression).Append(')');
                    break;
                default:
                    if (CatalogValues.Text(CatalogValues.At(row, 8)) is { } defaultValue)
                    {
                        definition.Append(" DEFAULT ").Append(RenderDefault(defaultValue, typeName));
                    }

                    break;
            }

            if (!CatalogValues.Flag(row[4]))
            {
                definition.Append(" NOT NULL");
            }

            lines.Add(definition.ToString());
            if (CatalogValues.Int32(row[6]) is { } position)
            {
                keys[position] = Q(name);
            }
        }

        if (keys.Count > 0)
        {
            lines.Add(string.Concat("  PRIMARY KEY (", string.Join(", ", keys.Values), ")"));
        }

        var sql = new StringBuilder("CREATE ").Append(isColumnTable ? "COLUMN" : "ROW").Append(" TABLE ").Append(Qualify(table))
            .Append(" (\n").AppendJoin(",\n", lines).Append("\n);");
        foreach (var statement in IndexStatements(table, indexRows))
        {
            sql.Append("\n\n").Append(statement);
        }

        if (tableComment is not null)
        {
            sql.Append("\n\nCOMMENT ON TABLE ").Append(Qualify(table)).Append(" IS ").Append(StringLiteral(tableComment)).Append(';');
        }

        foreach (var row in columnRows)
        {
            if (CatalogValues.NonEmpty(CatalogValues.At(row, 7)) is { } comment)
            {
                sql.Append("\n\n").Append(ColumnComment(table, CatalogValues.Text(row[0]) ?? string.Empty, comment)).Append(';');
            }
        }

        return sql.ToString();
    }

    /// <summary>
    /// CREATE INDEX for each index that is not the primary key's and whose type HANA can be asked for, from rows of
    /// INDEX_NAME, INDEX_TYPE, CONSTRAINT, COLUMN_NAME, ASCENDING_ORDER.
    /// </summary>
    public static IReadOnlyList<string> IndexStatements(ObjectName table, IReadOnlyList<object?[]> rows)
    {
        var statements = new List<string>();
        foreach (var index in HanaCatalog.MapIndexes(rows))
        {
            var type = index.Method ?? "BTREE";
            if (index.IsPrimary || !CreatableIndexTypes.Contains(type))
            {
                continue;
            }

            var keys = string.Join(", ", index.Columns.Select(c => c.EndsWith(" DESC", StringComparison.Ordinal) ? Q(c[..^5]) + " DESC" : Q(c)));
            statements.Add(string.Concat(
                "CREATE ", index.IsUnique ? "UNIQUE " : string.Empty, type, " INDEX ", Qualify(table with { Name = index.Name }), " ON ", Qualify(table), " (", keys, ");"));
        }

        return statements;
    }

    /// <summary>The catalog stores a string or date default bare; it is quoted again unless it is a function or a literal already.</summary>
    public static string RenderDefault(string value, string typeName)
    {
        var trimmed = value.Trim();
        return QuotedDefaultTypes.Contains(typeName.Trim().ToUpperInvariant())
            && !trimmed.StartsWith('\'')
            && !trimmed.StartsWith("N'", StringComparison.OrdinalIgnoreCase)
            && !DefaultFunctions.Contains(trimmed.ToUpperInvariant())
            ? StringLiteral(value)
            : value;
    }

    /// <summary>CREATE SEQUENCE from SYS.SEQUENCES.</summary>
    public static string SequenceDefinition(ObjectName sequence, object?[] row)
    {
        var sql = new StringBuilder("CREATE SEQUENCE ").Append(Qualify(sequence));
        Append(sql, " START WITH ", row[0]);
        Append(sql, " INCREMENT BY ", row[3]);
        Append(sql, " MINVALUE ", row[1]);
        Append(sql, " MAXVALUE ", row[2]);
        sql.Append(CatalogValues.Flag(row[4]) ? " CYCLE" : " NO CYCLE");
        var cache = CatalogValues.Int64(row[5]);
        sql.Append(cache is > 1 ? string.Create(CultureInfo.InvariantCulture, $" CACHE {cache}") : " NO CACHE");
        return sql.Append(';').ToString();

        static void Append(StringBuilder sql, string clause, object? value)
        {
            if (CatalogValues.Text(value)?.Trim() is { Length: > 0 } text)
            {
                sql.Append(clause).Append(text);
            }
        }
    }

    /// <summary>SYS.VIEWS keeps only the query; the CREATE around it is written here.</summary>
    public static string ViewDefinition(ObjectName view, string definition) =>
        string.Concat("CREATE VIEW ", Qualify(view), " AS\n", definition.Trim());

    /// <summary>Procedures, functions and triggers keep the statement that created them.</summary>
    public static string StoredDefinition(string definition)
    {
        var trimmed = definition.Trim();
        return trimmed.StartsWith("CREATE", StringComparison.OrdinalIgnoreCase) ? trimmed : "CREATE " + trimmed;
    }

    public static string Qualify(ObjectName name) => Dialect.Qualify(name);

    private static void AppendAction(StringBuilder sql, string clause, string? action)
    {
        var normalized = action is null ? null : string.Join(' ', action.Trim().ToUpperInvariant().Split((char[]?)null, StringSplitOptions.RemoveEmptyEntries));
        if (normalized is not null && ReferentialActions.Contains(normalized))
        {
            sql.Append(clause).Append(normalized);
        }
    }

    private static string? Trimmed(string? value) => string.IsNullOrWhiteSpace(value) ? null : value.Trim();

    private static string AlterTable(ObjectName table) => "ALTER TABLE " + Qualify(table);

    private static string Q(string identifier) => Dialect.QuoteIdentifier(identifier);

    private static string JoinQuoted(IReadOnlyList<string> names) => string.Join(", ", names.Select(Q));
}
