using System.Globalization;
using System.Text;
using TablePro.Core.Schema;
using TablePro.Core.Sql;

namespace TablePro.Drivers.Teradata;

/// <summary>The Teradata statements for each structure change, and the catalog text helpers. Pure, so tests pin them.</summary>
internal static class TeradataDdl
{
    /// <summary>Core has no macro kind; the session lists a macro as a procedure marked with this comment.</summary>
    public const string MacroMarker = "Macro";

    public static readonly IReadOnlyList<string> CommonDataTypes =
    [
        "INTEGER", "BIGINT", "VARCHAR(255) CHARACTER SET UNICODE", "VARCHAR(255)", "DECIMAL(18,2)", "DATE", "TIMESTAMP(6)",
        "CHAR(1)", "SMALLINT", "BYTEINT", "FLOAT", "NUMBER", "TIME(6)", "TIMESTAMP(6) WITH TIME ZONE", "CLOB", "BLOB",
        "VARBYTE(1024)", "JSON", "PERIOD(DATE)",
    ];

    private static SqlDialect Dialect => TeradataDialect.Instance;

    public static IReadOnlyList<string> Build(ObjectName table, SchemaChange change) => change switch
    {
        CreateTable create => CreateTable(create),
        AddColumn add => AddColumn(table, add.Column),
        DropColumn drop => [string.Concat(AlterTable(table), " DROP ", Q(drop.Column))],
        RenameColumn rename => [RenameColumn(table, rename.From, rename.To)],
        AlterColumn alter => AlterColumn(table, alter.Before, alter.After),
        CreateIndex index => [string.Concat("CREATE ", index.Index.IsUnique ? "UNIQUE " : string.Empty, "INDEX ", Q(index.Index.Name), " (", JoinQuoted(index.Index.Columns), ") ON ", Dialect.Qualify(table))],
        DropIndex index => [string.Concat("DROP INDEX ", Q(index.Index), " ON ", Dialect.Qualify(table))],
        AddForeignKey key => [string.Concat(AlterTable(table), " ADD ", ForeignKey(table, key.ForeignKey))],
        DropForeignKey key => [string.Concat(AlterTable(table), " DROP CONSTRAINT ", Q(key.Name))],
        RenameTable rename => [string.Concat("RENAME TABLE ", Dialect.Qualify(table), " TO ", Dialect.Qualify(table with { Name = rename.NewName }))],
        DropObject drop => DropObject(drop.Object) is { } sql ? [sql] : [],

        // Teradata has no TRUNCATE; DELETE ... ALL is its fast path, with no transient journal per row.
        TruncateTable => [string.Concat("DELETE FROM ", Dialect.Qualify(table), " ALL")],
        _ => [],
    };

    /// <summary>
    /// Identity is <c>GENERATED BY DEFAULT</c> so imported keys still insert. Teradata orders DEFAULT before NOT NULL.
    /// </summary>
    public static string ColumnSql(ColumnDefinition column)
    {
        var sql = new StringBuilder(Q(column.Name)).Append(' ').Append(column.DataType.Trim());
        if (column.IsIdentity)
        {
            sql.Append(" GENERATED BY DEFAULT AS IDENTITY");
        }
        else if (!string.IsNullOrWhiteSpace(column.DefaultExpression))
        {
            sql.Append(" DEFAULT ").Append(column.DefaultExpression.Trim());
        }

        if (!column.IsNullable || column.IsPrimaryKey)
        {
            sql.Append(" NOT NULL");
        }

        return sql.ToString();
    }

    /// <summary>
    /// A MULTISET table, so duplicate rows behave as in other engines. The primary key becomes the unique primary
    /// index, which is how Teradata both distributes and keys the rows; without one the table has no primary index.
    /// </summary>
    public static List<string> CreateTable(CreateTable change)
    {
        var keys = change.Columns.Where(c => c.IsPrimaryKey).Select(c => c.Name).ToList();
        var sql = new StringBuilder("CREATE MULTISET TABLE ").Append(Dialect.Qualify(change.Table)).Append(" (\n  ");
        sql.AppendJoin(",\n  ", change.Columns.Select(ColumnSql)).Append("\n)");
        sql.Append(keys.Count > 0 ? string.Concat("\nUNIQUE PRIMARY INDEX (", JoinQuoted(keys), ")") : "\nNO PRIMARY INDEX");

        var statements = new List<string> { sql.ToString() };
        foreach (var column in change.Columns)
        {
            if (!string.IsNullOrEmpty(column.Comment))
            {
                statements.Add(ColumnComment(change.Table, column.Name, column.Comment));
            }
        }

        return statements;
    }

    public static List<string> AddColumn(ObjectName table, ColumnDefinition column)
    {
        var statements = new List<string>(2) { string.Concat(AlterTable(table), " ADD ", ColumnSql(column)) };
        if (!string.IsNullOrEmpty(column.Comment))
        {
            statements.Add(ColumnComment(table, column.Name, column.Comment));
        }

        return statements;
    }

    public static string RenameColumn(ObjectName table, string from, string to) =>
        string.Concat(AlterTable(table), " RENAME ", Q(from), " TO ", Q(to));

    /// <summary>
    /// Teradata changes an existing column's attributes with ADD naming the column again; the server decides which
    /// changes it allows (a longer VARCHAR, a new default) and refuses the rest with its own message.
    /// </summary>
    public static List<string> AlterColumn(ObjectName table, ColumnDefinition before, ColumnDefinition after)
    {
        var statements = new List<string>(3);
        var changed = !string.Equals(before.DataType.Trim(), after.DataType.Trim(), StringComparison.OrdinalIgnoreCase)
            || before.IsNullable != after.IsNullable
            || !string.Equals(before.DefaultExpression?.Trim() ?? string.Empty, after.DefaultExpression?.Trim() ?? string.Empty, StringComparison.Ordinal);
        if (changed)
        {
            var column = after with { Name = before.Name, IsIdentity = false, IsPrimaryKey = false };
            statements.Add(string.Concat(AlterTable(table), " ADD ", ColumnSql(column)));
        }

        if (!string.Equals(before.Comment ?? string.Empty, after.Comment ?? string.Empty, StringComparison.Ordinal))
        {
            statements.Add(ColumnComment(table, before.Name, after.Comment));
        }

        if (!string.Equals(before.Name, after.Name, StringComparison.Ordinal))
        {
            statements.Add(RenameColumn(table, before.Name, after.Name));
        }

        return statements;
    }

    /// <summary>Teradata's referential constraints carry no ON DELETE or ON UPDATE action, so none is written.</summary>
    public static string ForeignKey(ObjectName table, ForeignKeyDefinition key)
    {
        var referenced = key.ReferencedTable.Schema is null ? key.ReferencedTable with { Schema = table.Schema } : key.ReferencedTable;
        var sql = new StringBuilder();
        if (!string.IsNullOrEmpty(key.Name))
        {
            sql.Append("CONSTRAINT ").Append(Q(key.Name)).Append(' ');
        }

        return sql.Append("FOREIGN KEY (").Append(JoinQuoted(key.Columns)).Append(") REFERENCES ").Append(Dialect.Qualify(referenced))
            .Append(" (").Append(JoinQuoted(key.ReferencedColumns)).Append(')').ToString();
    }

    public static string? DropObject(DatabaseObject obj)
    {
        var keyword = obj.Kind switch
        {
            ObjectKind.Table => "TABLE",
            ObjectKind.View => "VIEW",
            ObjectKind.Procedure when obj.Comment == MacroMarker => "MACRO",
            ObjectKind.Procedure => "PROCEDURE",
            ObjectKind.Function => "FUNCTION",
            ObjectKind.Trigger => "TRIGGER",
            _ => null,
        };

        return keyword is null ? null : string.Concat("DROP ", keyword, " ", Dialect.Qualify(obj.Name));
    }

    /// <summary>Teradata's COMMENT takes a string literal, so an empty one is what removes a comment.</summary>
    public static string ColumnComment(ObjectName table, string column, string? comment) =>
        string.Concat("COMMENT ON COLUMN ", Dialect.Qualify(table), ".", Q(column), " IS ", Dialect.StringLiteral(comment ?? string.Empty));

    /// <summary>The SHOW statement for a DBC.TablesV TableKind, or null when Teradata has none for it.</summary>
    public static string? ShowStatement(string tableKind, ObjectName name)
    {
        var keyword = tableKind.Trim() switch
        {
            "T" or "O" or "Q" => "TABLE",
            "V" => "VIEW",
            "M" => "MACRO",
            "P" or "E" => "PROCEDURE",
            "F" or "R" or "A" or "B" => "FUNCTION",
            "G" => "TRIGGER",
            "I" => "JOIN INDEX",
            "N" => "HASH INDEX",
            _ => null,
        };

        return keyword is null ? null : string.Concat("SHOW ", keyword, " ", Dialect.Qualify(name));
    }

    public static ObjectKind KindOf(string tableKind) => tableKind.Trim() switch
    {
        "V" => ObjectKind.View,
        "M" or "P" or "E" => ObjectKind.Procedure,
        "F" or "R" or "A" or "B" => ObjectKind.Function,
        "G" => ObjectKind.Trigger,
        _ => ObjectKind.Table,
    };

    /// <summary>A DBC.ColumnsV type code spelled as DDL. Unicode lengths are stored in bytes, two per character.</summary>
    public static string TypeName(string? code, int length, int totalDigits, int fractionalDigits, int charType)
    {
        var unicode = charType is 2 or 4;
        var characters = unicode ? length / 2 : length;
        var suffix = unicode ? " CHARACTER SET UNICODE" : string.Empty;
        return (code ?? string.Empty).Trim().ToUpperInvariant() switch
        {
            "I1" => "BYTEINT",
            "I2" => "SMALLINT",
            "I" => "INTEGER",
            "I8" => "BIGINT",
            "F" => "FLOAT",
            "D" => Format($"DECIMAL({totalDigits},{fractionalDigits})"),
            "N" => totalDigits is > 0 and < 40 ? Format($"NUMBER({totalDigits},{fractionalDigits})") : "NUMBER",
            "DA" => "DATE",
            "AT" => Format($"TIME({fractionalDigits})"),
            "TS" => Format($"TIMESTAMP({fractionalDigits})"),
            "TZ" => Format($"TIME({fractionalDigits}) WITH TIME ZONE"),
            "SZ" => Format($"TIMESTAMP({fractionalDigits}) WITH TIME ZONE"),
            "CF" => Format($"CHAR({characters})") + suffix,
            "CV" => Format($"VARCHAR({characters})") + suffix,
            "CO" => "CLOB" + suffix,
            "BF" => Format($"BYTE({length})"),
            "BV" => Format($"VARBYTE({length})"),
            "BO" => "BLOB",
            "JN" => "JSON",
            "XM" => "XML",
            "UT" => "UDT",
            "PD" => "PERIOD(DATE)",
            "PT" => "PERIOD(TIME)",
            "PS" => "PERIOD(TIMESTAMP)",
            "PM" => "PERIOD(TIMESTAMP WITH TIME ZONE)",
            "YR" => "INTERVAL YEAR",
            "YM" => "INTERVAL YEAR TO MONTH",
            "MO" => "INTERVAL MONTH",
            "DY" => "INTERVAL DAY",
            "DH" => "INTERVAL DAY TO HOUR",
            "DM" => "INTERVAL DAY TO MINUTE",
            "DS" => "INTERVAL DAY TO SECOND",
            "HR" => "INTERVAL HOUR",
            "HM" => "INTERVAL HOUR TO MINUTE",
            "HS" => "INTERVAL HOUR TO SECOND",
            "MI" => "INTERVAL MINUTE",
            "MS" => "INTERVAL MINUTE TO SECOND",
            "SC" => "INTERVAL SECOND",
            "" => "UNKNOWN",
            var other => other,
        };
    }

    public static string IndexDescription(string indexType) => indexType.Trim() switch
    {
        "P" => "PRIMARY INDEX",
        "Q" => "PARTITIONED PRIMARY INDEX",
        "K" => "PRIMARY KEY",
        "U" => "UNIQUE",
        "S" => "SECONDARY",
        "V" => "VALUE-ORDERED SECONDARY",
        "H" => "HASH-ORDERED SECONDARY",
        "O" => "VALUE-ORDERED COVERING",
        "J" => "JOIN INDEX",
        "N" => "HASH INDEX",
        var other => other,
    };

    public static string TriggerTiming(string? actionTime) => actionTime?.Trim() switch
    {
        "B" => "BEFORE",
        "I" => "INSTEAD OF",
        _ => "AFTER",
    };

    public static string TriggerEvent(string? code) => code?.Trim() switch
    {
        "I" => "INSERT",
        "U" => "UPDATE",
        "D" => "DELETE",
        var other => other ?? string.Empty,
    };

    private static string Format(FormattableString value) => value.ToString(CultureInfo.InvariantCulture);

    private static string AlterTable(ObjectName table) => "ALTER TABLE " + Dialect.Qualify(table);

    private static string Q(string identifier) => Dialect.QuoteIdentifier(identifier);

    private static string JoinQuoted(IReadOnlyList<string> names) => string.Join(", ", names.Select(Q));
}
