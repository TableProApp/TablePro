    [Fact]
    public void ConnectionStringDialsTheTunnelWithTheLogin()
    {
        var builder = new TdConnectionStringBuilder(TeradataConnectionStringFactory.Build(Profiles.Tunnelled(DatabaseEngine.Teradata)));

        Assert.Equal("127.0.0.1", builder.DataSource);
        Assert.Equal(15432, builder.PortNumber);
