    [Fact]
    public void ColumnStatements()
    {
        Assert.Equal(["ALTER TABLE \"sales\".\"orders\" ADD \"qty\" INTEGER DEFAULT 0 NOT NULL"], Build(new AddColumn(new ColumnDefinition("qty", "INTEGER", false, "0"))));
        Assert.Equal(["ALTER TABLE \"sales\".\"orders\" DROP \"qty\""], Build(new DropColumn("qty")));
        Assert.Equal(["ALTER TABLE \"sales\".\"orders\" RENAME \"a\" TO \"b\""], Build(new RenameColumn("a", "b")));
    }

    [Fact]
    public void AlterColumnRestatesItWithAdd()
    {
        var before = new ColumnDefinition("name", "VARCHAR(50)", false);

        Assert.Equal(["ALTER TABLE \"sales\".\"orders\" ADD \"name\" VARCHAR(100) NOT NULL"], Build(new AlterColumn(before, before with { DataType = "VARCHAR(100)" })));
        Assert.Equal(["ALTER TABLE \"sales\".\"orders\" ADD \"name\" VARCHAR(50) DEFAULT 'n'"], Build(new AlterColumn(before, before with { DefaultExpression = "'n'", IsNullable = true })));
        Assert.Equal(
            ["COMMENT ON COLUMN \"sales\".\"orders\".\"name\" IS 'who'", "ALTER TABLE \"sales\".\"orders\" RENAME \"name\" TO \"label\""],
            Build(new AlterColumn(before, before with { Name = "label", Comment = "who" })));
        Assert.Empty(Build(new AlterColumn(before, before)));
    }

    [Fact]
    public void IndexAndKeyStatements()
    {
        Assert.Equal(["CREATE UNIQUE INDEX \"ix\" (\"a\", \"b\") ON \"sales\".\"orders\""], Build(new CreateIndex(new IndexDefinition("ix", ["a", "b"], true))));
        Assert.Equal(["CREATE INDEX \"ix\" (\"a\") ON \"sales\".\"orders\""], Build(new CreateIndex(new IndexDefinition("ix", ["a"]))));
        Assert.Equal(["DROP INDEX \"ix\" ON \"sales\".\"orders\""], Build(new DropIndex("ix")));
        Assert.Equal(
            ["ALTER TABLE \"sales\".\"orders\" ADD CONSTRAINT \"fk\" FOREIGN KEY (\"customer_id\") REFERENCES \"sales\".\"customers\" (\"id\")"],
            Build(new AddForeignKey(new ForeignKeyDefinition("fk", ["customer_id"], new ObjectName(null, "customers"), ["id"], "CASCADE", "CASCADE"))));
        Assert.Equal(["ALTER TABLE \"sales\".\"orders\" DROP CONSTRAINT \"fk\""], Build(new DropForeignKey("fk")));
    }

    [Fact]
