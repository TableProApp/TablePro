    [Fact]
    public void PrimaryKeyRanksAboveAUniquePrimaryIndex()
    {
        var keyed = TeradataSession.KeyColumns([(Column("a"), 2), (Column("b"), 1), (Column("c"), 0)]);
        var indexed = TeradataSession.KeyColumns([(Column("a"), 2), (Column("b"), 2), (Column("c"), 0)]);
        var none = TeradataSession.KeyColumns([(Column("a"), 0)]);

        Assert.Equal(["b"], keyed.Where(c => c.IsPrimaryKey).Select(c => c.Name));
        Assert.Equal(["a", "b"], indexed.Where(c => c.IsPrimaryKey).Select(c => c.Name));
        Assert.DoesNotContain(none, c => c.IsPrimaryKey);
        Assert.Equal([0, 1, 2], keyed.Select(c => c.Ordinal));
    }

