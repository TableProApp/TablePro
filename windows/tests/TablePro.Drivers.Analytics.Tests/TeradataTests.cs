    [Fact]
    public void CoreParametersArePositionalMarkersTheProviderAccepts()
    {
        var filter = new BrowseFilter([new FilterRule("id", FilterOperator.Equals, "1"), new FilterRule("name", FilterOperator.Contains, "x")]);
        var spec = TeradataDialect.Instance.BuildBrowse(new BrowseRequest(Orders, filter, [], 0, 50));

        Assert.Equal(spec.Parameters.Count, spec.Text.Count(c => c == '?'));
        Assert.All(spec.Parameters, p => Assert.Equal("?", p.Key));

        // The provider binds by position and refuses only the same parameter object twice, not a repeated name.
        using var command = new TdCommand();
        foreach (var (name, value) in spec.Parameters)
        {
            var parameter = command.CreateParameter();
            parameter.ParameterName = name;
            parameter.Value = value;
            command.Parameters.Add(parameter);
        }

        Assert.Equal(2, command.Parameters.Count);
    }

    [Fact]
    public void CreateTableIsMultisetWithTheKeyAsUniquePrimaryIndex()
    {
        var change = new CreateTable(Orders,
        [
            new ColumnDefinition("id", "BIGINT", IsPrimaryKey: true, IsIdentity: true),
            new ColumnDefinition("name", "VARCHAR(100) CHARACTER SET UNICODE", false, "'x'"),
            new ColumnDefinition("note", "CLOB", Comment: "it's"),
        ]);

        Assert.Equal(
            [
                "CREATE MULTISET TABLE \"sales\".\"orders\" (\n  \"id\" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,\n  \"name\" VARCHAR(100) CHARACTER SET UNICODE DEFAULT 'x' NOT NULL,\n  \"note\" CLOB\n)\nUNIQUE PRIMARY INDEX (\"id\")",
                "COMMENT ON COLUMN \"sales\".\"orders\".\"note\" IS 'it''s'",
            ],
            Build(change));
    }

    [Fact]
